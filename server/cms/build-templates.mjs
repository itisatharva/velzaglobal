// Builds the CMS article templates from the existing live article pages, so CMS-rendered pages
// share the exact shell (head assets, menu, footer, scripts) of each region's static articles.
//
//   node server/cms/build-templates.mjs          (run from the repository root)
//
// Four regions of each reference page are replaced with markers; everything else is copied
// byte-for-byte:
//   <!--CMS:SEO-->      the "SEO / Social Metadata" block in <head>
//   <!--CMS:ARTICLE-->  the inner HTML of <div class="post-content pb-5">
//   <!--CMS:RELATED-->  the <section class="vg-related"> block
//   <!--CMS:NAV-->      the <section class="article-navigation"> block (the reference news page
//                       hard-codes a "next article" link, so it cannot be shared verbatim)
//
// It also writes templates/index.mjs, which exports the same templates as strings so the Cloudflare
// Worker can bundle them (cPanel never deploys server/, so the Worker cannot read these files).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MARKERS } from './markers.mjs';

export { MARKERS };
export const REGIONS = ['hk', 'in', 'ph'];
export const REFERENCE_PAGES = {
  blogs: 'blogs/global-brand-partnership.html',
  news: 'news/tonino-lamborghini-velza-global-partnership-philippines.html',
};

const once = (haystack, needle, from = 0) => {
  const i = haystack.indexOf(needle, from);
  if (i === -1) throw new Error(`marker not found: ${needle}`);
  if (haystack.indexOf(needle, i + needle.length) !== -1 && from === 0) throw new Error(`marker not unique: ${needle}`);
  return i;
};

/**
 * Splits a reference page into the template plus the three replaced slices.
 * Returns { template, slices: { seo, article, related } }; template with the slices put back equals the page.
 */
export const extractTemplate = (page) => {
  const seoOpen = '<!-- SEO / Social Metadata -->';
  const seoStart = once(page, seoOpen) + seoOpen.length;
  const seoEnd = once(page, '<!-- End SEO / Social Metadata -->');

  const bodyOpen = '<div class="post-content pb-5">';
  const bodyStart = once(page, bodyOpen) + bodyOpen.length;
  const articleEnd = once(page, '</article>', bodyStart);
  const bodyEnd = page.lastIndexOf('</div>', articleEnd);
  if (bodyEnd <= bodyStart) throw new Error('post-content closing tag not found');

  const relStart = once(page, '<section class="vg-related"');
  const relEnd = page.indexOf('</section>', relStart) + '</section>'.length;
  if (relEnd < relStart + 10) throw new Error('vg-related closing tag not found');

  const navStart = once(page, '<section class="article-navigation');
  const navEnd = page.indexOf('</section>', navStart) + '</section>'.length;
  if (navEnd < navStart + 10) throw new Error('article-navigation closing tag not found');

  if (!(seoEnd < bodyStart && bodyEnd < relStart && relEnd <= navStart)) throw new Error('unexpected section order');
  const slices = {
    seo: page.slice(seoStart, seoEnd),
    article: page.slice(bodyStart, bodyEnd),
    related: page.slice(relStart, relEnd),
    nav: page.slice(navStart, navEnd),
  };
  const template =
    page.slice(0, seoStart) + MARKERS.seo +
    page.slice(seoEnd, bodyStart) + MARKERS.article +
    page.slice(bodyEnd, relStart) + MARKERS.related +
    page.slice(relEnd, navStart) + MARKERS.nav +
    page.slice(navEnd);
  return { template, slices };
};

export const templatePath = (root, region, type) => join(root, 'server', 'cms', 'templates', region, `${type}.html`);

export const templateModulePath = (root) => join(root, 'server', 'cms', 'templates', 'index.mjs');

export const buildTemplates = (root) => {
  const written = [];
  const all = {};
  for (const region of REGIONS) {
    all[region] = {};
    for (const [type, rel] of Object.entries(REFERENCE_PAGES)) {
      const page = readFileSync(join(root, 'regions', region, rel), 'utf8');
      const { template } = extractTemplate(page);
      const out = templatePath(root, region, type);
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, template);
      written.push(out);
      all[region][type] = template;
    }
  }
  const moduleOut = templateModulePath(root);
  writeFileSync(moduleOut, `// Generated by server/cms/build-templates.mjs - do not edit.\nexport const TEMPLATES = ${JSON.stringify(all)};\n`);
  written.push(moduleOut);
  return written;
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  for (const f of buildTemplates(root)) console.log(`wrote ${f}`);
}
